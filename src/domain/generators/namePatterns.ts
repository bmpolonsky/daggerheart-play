export function composedNames(style: CharacterNameStyle, gender: 'male' | 'female'): string[] {
  return NAME_PATTERNS[style].flatMap((group) => group.starts.flatMap((start) =>
    group[gender].map((ending) => start + ending)))
    .filter((name) => !/([а-яё]{2,3})\1/iu.test(name) && !/([а-яё])\1\1/iu.test(name) && !['Кэк', 'Дома'].includes(name));
}
