import { expect, test } from '@playwright/test';
import { createExperience } from '../../src/domain/rules/factories';
import { createPopulatedGameDocument, importGameDocument } from './filled-game-helpers';
import { openGmGame } from './game-route-helpers';
import { openUnifiedFormulaEditor } from './unified-formula-helpers';

const before = process.env.TRAY_GROUPS_BEFORE === '1';
for (const width of [1180, 400, 320]) test(`tray adjustments retain names, help and keyboard control at ${width}`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 757 }); await openGmGame(page);
  const gameDocument = createPopulatedGameDocument();
  const hero = gameDocument.files['data/characters.json'].entities['e2e-character-cadsuane'];
  hero.name = 'QA Кадсуанэ — очень длинное имя для проверки панели'; hero.traits.agility = 2; hero.hope.value = 1;
  hero.experiences = [createExperience('Длинный опыт для проверки переносов и читаемости', 2), createExperience('Верный товарищ', 2)];
  await importGameDocument(page, gameDocument, 'tray-adjustment-groups.dhgame', hero.name);
  const layers = page.getByLabel('Слой интерфейса');
  if (await layers.isVisible()) await layers.getByRole('button', { name: 'Сцена', exact: true }).click();
  await page.getByRole('button', { name: 'Открыть панель костей', exact: true }).click();
  const tray = page.getByRole('region', { name: 'Подготовка броска', exact: true });
  const actor = tray.getByRole('combobox', { name: 'Исполнитель броска', exact: true });
  await actor.selectOption('character:e2e-character-cadsuane');
  const trait = tray.getByRole('combobox', { name: 'Характеристика броска', exact: true });
  await trait.selectOption('agility'); await tray.getByRole('button', { name: 'Опыт', exact: true }).click();
  await expect(tray.getByLabel('Итоговая формула', { exact: true })).toHaveText('2d12+2');
  await page.screenshot({ path: info.outputPath(`adjustments-${before ? 'before' : 'after'}-${width}.png`) });
  if (before) return;
  const traitGroup = tray.getByRole('group', { name: 'Характеристика и справка', exact: true });
  const experienceGroup = tray.getByRole('group', { name: 'Опыт и справка', exact: true });
  const traitBounds = await trait.boundingBox();
  const modifierBounds = await tray.getByRole('button', { name: 'Увеличить модификатор', exact: true }).boundingBox();
  const toggleBounds = await experienceGroup.boundingBox();
  expect(Math.abs(traitBounds!.y - modifierBounds!.y)).toBeLessThan(10);
  expect(toggleBounds!.y).toBeGreaterThan(traitBounds!.y + traitBounds!.height - 1);
  await expect(traitGroup.getByRole('combobox')).toHaveAttribute('title', 'Проворность +2');
  const metrics = await trait.evaluate((element: HTMLSelectElement) => {
    const style = getComputedStyle(element), canvas = document.createElement('canvas'), context = canvas.getContext('2d')!;
    context.font = `${style.fontWeight} ${style.fontSize} ${style.fontFamily}`;
    return { text: context.measureText(element.selectedOptions[0].text).width,
      available: element.clientWidth - parseFloat(style.paddingLeft) - parseFloat(style.paddingRight),
      appearance: style.appearance, arrow: style.backgroundImage, arrowGutter: parseFloat(style.paddingRight) };
  });
  expect(metrics.appearance).toBe('none');
  expect(metrics.arrow).toContain('data:image/svg+xml');
  expect(metrics.arrowGutter).toBeGreaterThanOrEqual(22);
  expect(metrics.available).toBeGreaterThanOrEqual(metrics.text + 4);
  await trait.focus(); await trait.press('Space');
  await page.screenshot({ path: info.outputPath(`select-open-${width}.png`) });
  await trait.press('Escape'); await expect(trait).toHaveValue('agility');
  expect(await tray.evaluate(element => element.scrollWidth - element.clientWidth)).toBeLessThanOrEqual(1);
  await trait.focus(); await trait.press('ArrowDown'); await trait.press('ArrowUp'); await expect(trait).toHaveValue('agility');
  await trait.press('Tab');
  expect(await traitGroup.evaluate(element => element.contains(document.activeElement))).toBe(true);
  await experienceGroup.getByRole('button', { name: 'Опыт', exact: true }).focus();
  await page.keyboard.press('Space'); await expect(tray.getByRole('checkbox', { name: 'Верный товарищ +2', exact: true })).toHaveCount(0);
  await page.keyboard.press('Space'); await page.keyboard.press('Tab');
  expect(await experienceGroup.evaluate(element => element.contains(document.activeElement))).toBe(true);
  const modifier = tray.getByRole('group', { name: 'Доп. модификатор', exact: true }).getByLabel('Модификатор', { exact: true });
  await expect(modifier).toHaveValue('+0'); await modifier.fill('3'); await expect(tray.getByLabel('Итоговая формула', { exact: true })).toHaveText('2d12+5');
  await tray.getByRole('checkbox', { name: 'Длинный опыт для проверки переносов и читаемости +2', exact: true }).check();
  await tray.getByRole('checkbox', { name: 'Верный товарищ +2', exact: true }).check();
  await expect(tray.getByRole('button', { name: 'Бросить', exact: true })).toBeDisabled();
  const experienceToggle = experienceGroup.getByRole('button', { name: 'Опыт +4', exact: true });
  await expect(experienceToggle).toHaveAttribute('aria-expanded', 'true');
  await expect(tray.getByText('Цена опыта: 2 Надежды', { exact: true })).toBeVisible();
  await experienceToggle.click();
  await expect(tray.getByRole('checkbox')).toHaveCount(0);
  await expect(tray.getByText('Длинный опыт для проверки переносов и читаемости', { exact: true })).toHaveCount(0);
  await expect(tray.getByLabel('Итоговая формула', { exact: true })).toHaveText('2d12+9');
  await page.screenshot({ path: info.outputPath(`compact-collapsed-${width}.png`) });
  await experienceToggle.click();

  await tray.getByRole('checkbox', { name: 'Верный товарищ +2', exact: true }).uncheck();
  await expect(tray.getByRole('button', { name: 'Бросить', exact: true })).toBeEnabled();
  await expect(tray.getByLabel('Итоговая формула', { exact: true })).toHaveText('2d12+7');
  await actor.selectOption('gm');
  await expect(tray.getByRole('group', { name: 'Доп. модификатор', exact: true })).toHaveCount(0);
  const flat = tray.getByRole('group', { name: 'Модификатор', exact: true }).getByLabel('Модификатор', { exact: true });
  await flat.fill('3'); await expect(tray.getByLabel('Итоговая формула', { exact: true })).toHaveText('1d20+3');
  const formula = await openUnifiedFormulaEditor(tray); await formula.fill('1d20+5'); await formula.blur(); await expect(flat).toHaveValue('+5');
});
