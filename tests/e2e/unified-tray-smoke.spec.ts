import { openUnifiedFormulaEditor } from './unified-formula-helpers';
import { readFileSync } from 'node:fs';
import { expect, test } from '@playwright/test';
import { createDomainCard, createExperience, createWeapon } from '../../src/domain/rules/factories';
import { createPopulatedGameDocument, filledCharacterName, importGameDocument } from './filled-game-helpers';
import { openGmGame } from './game-route-helpers';

test('weapon action, damage and contextual Chaos all prepare one editable tray without autoroll', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  await openGmGame(page);
  const document = createPopulatedGameDocument();
  const actor = document.files['data/characters.json'].entities['e2e-character-cadsuane'];
  actor.proficiency = 2;
  actor.spellcastTrait = 'instinct';
  actor.traits.instinct = 2;
  actor.hope.value = 3;
  actor.stress.marked = 0;
  actor.experiences = [{ ...createExperience('QA опыт', 2), id: 'qa-exp' }];
  actor.weapons = [createWeapon({ name: 'QA Клинок трея', trait: 'finesse', damageFormula: '1d6+3' })];
  const catalog = JSON.parse(readFileSync(new URL('../../public/data/domain-cards.json', import.meta.url), 'utf8'));
  const chaos = catalog.data.find((card: { slug: string }) => card.slug === 'unleash-chaos');
  actor.domainCards = [createDomainCard({ id: 'qa-chaos', sourceId: 'domain-card:unleash-chaos', name: chaos.name,
    domain: 'Arcana', inLoadout: true, text: chaos.features.map((feature: { main_body: string }) => feature.main_body).join('\n\n'), tokens: { value: 0, max: 2 } })];
  await importGameDocument(page, document, 'unified-tray-smoke.dhgame');
  await page.getByLabel('Участники сцены').locator('.player-roster__item').filter({ hasText: filledCharacterName }).first().click();
  const sheet = page.getByLabel('Персонаж игрока');
  await page.getByLabel('Разделы листа персонажа').getByRole('button', { name: 'Оружие', exact: true }).click();
  const weapon = sheet.locator('#player-sheet-actions .dh-list-item').filter({ hasText: 'QA Клинок трея' });
  const rollsBefore = await page.locator('.player-activity-event--roll').count();
  await weapon.getByRole('button', { name: 'Атака', exact: true }).click();
  const tray = page.getByRole('region', { name: 'Подготовка броска', exact: true });
  await openUnifiedFormulaEditor(tray);
  await expect(tray).toHaveCount(1);
  await expect(tray).toBeVisible();
  await expect(tray.getByRole('combobox', { name: 'Исполнитель броска', exact: true })).toHaveValue('character:e2e-character-cadsuane');
  await expect(tray.getByLabel('Формула броска', { exact: true })).toHaveValue(/2d12/);
  await page.screenshot({ path: testInfo.outputPath('tray-normal.png') });
  await tray.getByRole('button', { name: 'Опыт', exact: true }).click();
  await tray.getByRole('checkbox', { name: /QA опыт.*\+2/ }).check();
  await tray.getByLabel('Модификатор', { exact: true }).fill('3');
  await expect(tray).toContainText(/1.*Надежд/);
  await page.screenshot({ path: testInfo.outputPath('tray-experience-cost.png') });
  await expect(page.locator('.player-activity-event--roll')).toHaveCount(rollsBefore);
  await weapon.getByRole('button', { name: 'Урон', exact: true }).click();
  await expect(tray.getByRole('button', { name: 'Заменить подготовленный бросок', exact: true })).toBeVisible();
  await tray.getByRole('button', { name: 'Заменить подготовленный бросок', exact: true }).click();
  await expect(tray.getByLabel('Формула броска', { exact: true })).toHaveValue('2d6+3');
  await expect(tray.getByLabel('Модификатор', { exact: true })).toHaveValue('3');
  await expect(tray.getByRole('checkbox', { name: /QA опыт/ })).toHaveCount(0);
  await tray.getByRole('button', { name: 'Закрыть панель броска', exact: true }).click();
  await page.getByLabel('Разделы листа персонажа').getByRole('button', { name: 'Карты', exact: true }).click();
  await sheet.locator('.dh-list-item').filter({ hasText: chaos.name }).click();
  const preview = page.getByRole('complementary', { name: 'Предпросмотр', exact: true });
  await preview.getByRole('button', { name: 'd10', exact: true }).click();
  await expect(tray).toBeVisible();
  await expect(tray.getByRole('button', { name: 'Бросить', exact: true })).toBeDisabled();
  await tray.getByRole('spinbutton', { name: /^Жетонов потрачено на эту атаку/ }).fill('2');
  await expect(tray.getByLabel('Итоговая формула', { exact: true })).toHaveText('2d10');
  const originalBox = (await tray.boundingBox())!;
  const handle = (await page.getByTestId('dice-tray-drag-handle').boundingBox())!;
  await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2);
  await page.mouse.down();
  await page.mouse.move(handle.x + handle.width / 2 - 420, handle.y + handle.height / 2 - 70, { steps: 8 });
  await page.mouse.up();
  expect((await tray.boundingBox())!.x).toBeLessThan(originalBox.x - 100);
  await tray.getByRole('button', { name: 'Добавить d6', exact: true }).click();
  await expect(tray.getByLabel('Итоговая формула', { exact: true })).toHaveText(/2d10.*1d6/);
  await expect(preview).toBeVisible();
  await expect(page.locator('.player-activity-event--roll')).toHaveCount(rollsBefore);
  await expect(page.getByLabel('Подтверждение броска', { exact: true })).toHaveCount(0);
  await expect(page.getByLabel('Подтверждение атаки противника', { exact: true })).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath('tray-chaos-card.png') });
  await tray.getByRole('button', { name: 'Закрыть панель броска', exact: true }).click();
  await page.getByRole('button', { name: 'Открыть панель костей', exact: true }).click();
  expect(Math.abs((await tray.boundingBox())!.x - originalBox.x)).toBeLessThan(4);
  await expect(tray.getByLabel('Итоговая формула', { exact: true })).toHaveText(/2d10.*1d6/);
  await tray.getByRole('button', { name: 'Бросить', exact: true }).click();
  await expect(page.locator('.player-activity-event--roll')).toHaveCount(rollsBefore + 1);
});
