import { openUnifiedFormulaEditor } from './unified-formula-helpers';
import { expect, test } from '@playwright/test';
import { createExperience, createWeapon } from '../../src/domain/rules/factories';
import { createPopulatedGameDocument, filledAdversaryName, filledCharacterName, importGameDocument } from './filled-game-helpers';
import { openGmGame } from './game-route-helpers';

test('NPC attack and damage prepare one tray, with Fear payment only on attack submit', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  await openGmGame(page);
  const document = createPopulatedGameDocument();
  document.files['data/game.json'].fear = 3;
  const npc = document.files['data/encounter.json'].adversaries['e2e-adversary-ooze'];
  npc.attackModifier = 3;
  npc.experiences = [{ ...createExperience('Воровство', 2), id: 'qa-npc-exp' }];
  npc.standardAttack.damageFormula = '2d8+4';
  await importGameDocument(page, document, 'unified-npc.dhgame');
  await page.locator('.player-roster__item').filter({ hasText: filledAdversaryName }).first().click();
  const sheet = page.getByLabel('Противник мастера', { exact: true });
  const tray = page.getByRole('region', { name: 'Подготовка броска', exact: true });
  await openUnifiedFormulaEditor(tray);
  await sheet.getByRole('button', { name: 'Атака', exact: true }).click();
  await expect(tray.getByLabel('Формула броска', { exact: true })).toHaveValue('1d20+3');
  await tray.getByRole('button', { name: 'Опыт', exact: true }).click();
  await tray.getByRole('checkbox', { name: 'Воровство +2', exact: true }).check();
  await expect(tray.getByLabel('Формула броска', { exact: true })).toHaveValue('1d20+5');
  await tray.getByRole('button', { name: 'Добавить d6', exact: true }).click();
  await expect(tray.getByLabel('Формула броска', { exact: true })).toHaveValue('1d20+1d6+5');
  await expect(tray.getByRole('button', { name: 'Сделать ручным броском', exact: true })).toHaveCount(0);
  await expect(tray.getByRole('region', { name: 'Итог броска' })).toContainText('1 Страха');
  await expect(page.locator('.player-fear-track__value')).toHaveText('3/12');
  await expect(page.locator('.player-activity-event--roll')).toHaveCount(0);
  await tray.getByRole('button', { name: 'Бросить', exact: true }).click();
  await expect(page.locator('.player-activity-event--roll')).toHaveCount(1);
  await expect(page.locator('.player-fear-track__value')).toHaveText('2/12');
  await sheet.getByRole('button', { name: 'Урон', exact: true }).click();
  await expect(tray.getByLabel('Формула броска', { exact: true })).toHaveValue('2d8+4');
  await expect(tray.getByRole('checkbox', { name: 'Воровство +2', exact: true })).toHaveCount(0);
  await expect(tray.getByRole('button', { name: 'Убрать дополнительный d6', exact: true })).toHaveCount(0);
  await expect(tray.getByRole('region', { name: 'Итог броска' })).not.toContainText('Страха');
  await expect(page.locator('.player-activity-event--roll')).toHaveCount(1);
  await tray.getByRole('button', { name: 'Бросить', exact: true }).click();
  await expect(page.locator('.player-activity-event--roll')).toHaveCount(2);
  await expect(page.locator('.player-fear-track__value')).toHaveText('2/12');
  await expect(page.getByLabel('Подтверждение броска', { exact: true })).toHaveCount(0);
});

test('critical damage shows its maximum-dice bonus before submit and in the chat without doubling flat modifiers', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  await openGmGame(page);
  const document = createPopulatedGameDocument();
  document.files['data/characters.json'].entities['e2e-character-cadsuane'].weapons = [createWeapon({ name: 'QA Крит', damageFormula: '1d10+3' })];
  await importGameDocument(page, document, 'unified-critical.dhgame');
  await page.locator('.player-roster__item').filter({ hasText: filledCharacterName }).first().click();
  await page.getByLabel('Разделы листа персонажа').getByRole('button', { name: 'Оружие', exact: true }).click();
  await page.getByLabel('Персонаж игрока').locator('.dh-list-item').filter({ hasText: 'QA Крит' }).getByRole('button', { name: 'Урон', exact: true }).click();
  const tray = page.getByRole('region', { name: 'Подготовка броска', exact: true });
  await expect(tray.getByLabel('Формула броска', { exact: true })).toHaveCount(0);
  const critical = tray.getByRole('checkbox', { name: 'Критический урон', exact: true });
  const summary = tray.getByRole('region', { name: 'Итог броска' });
  await critical.check();
  await expect(summary.getByLabel('Итоговая формула', { exact: true })).toHaveText('1d10+13');
  await expect(summary).toContainText('Крит: +10');
  await critical.uncheck();
  await expect(summary).not.toContainText('+10');
  await critical.check();
  await tray.getByRole('button', { name: 'Бросить', exact: true }).click();
  const roll = page.locator('.player-activity-event--roll').first();
  await expect(roll).toContainText('Крит +10');
  await roll.getByRole('button', { name: 'Подробности броска', exact: true }).click();
  await expect(roll).toContainText(/1d10\s*\+\s*3\s*\+\s*10\s*\(крит\)/);
});
