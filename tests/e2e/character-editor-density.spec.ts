import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { expect, test } from '@playwright/test';
import { createPopulatedGameDocument, importGameDocument } from './filled-game-helpers';
import { openGmGame } from './game-route-helpers';
import { openGameLibrary } from './tools-helpers';
const before = process.env.EDITOR_DENSITY_BEFORE === '1';
const out = () => test.info().outputPath();
const catalog = (name: string) => JSON.parse(readFileSync(new URL(`../../public/data/${name}.json`, import.meta.url), 'utf8')).data;
for (const [width, bonus] of [[1440,true],[1180,true],[500,true],[390,true],[1180,false]] as const) test(`compact editor at ${width} bonus=${bonus}`, async ({page}) => {
  mkdirSync(out(),{recursive:true});
  await page.setViewportSize({width,height:757});await openGmGame(page);
  const doc=createPopulatedGameDocument(),hero=doc.files['data/characters.json'].entities['e2e-character-cadsuane'];
  doc.files['data/characters.json'].entities['e2e-character-ran'].name='Кадсуанэ';
  hero.name='QA — Кадсуанэ с очень длинным именем';hero.className='Bard';hero.classSlug='bard';hero.classSourceId='class:bard';hero.classDisplayName='Бард';
  hero.evasion=9;hero.hp={max:5,marked:0};hero.sheetCards=[];hero.domainCards=[];
  if(bonus){const giant=catalog('ancestries').find((x:any)=>x.slug==='giant');hero.sheetCards=[{id:'qa-giant',kind:'ancestryFeature',name:giant.features[0].name,text:giant.features[0].main_body}];}
  const armor=catalog('equipment').find((x:any)=>x.slug===(bonus?'gambeson-armor':'leather-armor'));
  hero.armor={...hero.armor,name:armor.name,sourceSlug:armor.slug,equipped:true,score:armor.armor_score,markedSlots:0,baseMajor:armor.base_thresholds[0],baseSevere:armor.base_thresholds[1],feature:armor.features.map((f:any)=>`${f.name}: ${f.main_body}`).join('\n'),featureText:''};
  await importGameDocument(page,doc,'density.dhgame');const library=await openGameLibrary(page);
  await library.getByLabel('Разделы библиотеки').getByRole('button',{name:'Персонажи',exact:true}).click();
  await library.getByRole('navigation',{name:'Ростер персонажей',exact:true}).getByRole('button',{name:hero.name,exact:true}).click();
  const editor=library.getByRole('region',{name:'Редактор персонажа',exact:true});
  await editor.getByLabel('Разделы листа персонажа').getByRole('button',{name:'Характеристики',exact:true}).click();
  const prefix=`${before?'before':'after'}-${width}-${bonus}`;
  await page.screenshot({path:`${out()}/${prefix}-view.png`});
  await editor.getByRole('button',{name:'Редактировать',exact:true}).click();
  await page.screenshot({path:`${out()}/${prefix}-edit.png`});
  const metrics=await editor.evaluate(el=>{
    const traits=Array.from(el.querySelectorAll('.trait-card')).map(e=>{const r=e.getBoundingClientRect();return{x:r.x,y:r.y,w:r.width,h:r.height,overflow:e.scrollWidth-e.clientWidth};});
    const workspace=el.querySelector('.character-editor-workspace')!.getBoundingClientRect();
    const advanced=el.querySelector('.character-editor-advanced')!.getBoundingClientRect();
    const t=el.querySelector('.character-editor-statline')!.getBoundingClientRect();
    return{traits,workspaceWidth:workspace.width,advancedTop:advanced.top,threshold:{x:t.x,y:t.y},overflow:el.scrollWidth-el.clientWidth};
  });writeFileSync(`${out()}/${prefix}-metrics.json`,JSON.stringify(metrics,null,2));
  if(before)return;
  expect(metrics.overflow).toBeLessThanOrEqual(1);expect(metrics.traits.every(t=>t.overflow<=1)).toBe(true);
  expect(new Set(metrics.traits.map(t=>Math.round(t.x))).size).toBe(metrics.workspaceWidth>360?3:2);
  if(metrics.workspaceWidth>=650)expect(metrics.threshold.x).toBeGreaterThan(metrics.traits[2].x);
  else expect(metrics.threshold.y).toBeGreaterThan(metrics.traits[5].y);
  await expect(editor.getByLabel('Ключевые параметры',{exact:true})).toHaveCount(0);
  const evasion=editor.getByLabel('Базовое уклонение',{exact:true});await expect(evasion).toHaveValue('9');
  await expect(evasion.locator('..')).toContainText(`Итог: ${bonus?10:9}`);
  await evasion.fill('10');await evasion.press('Tab');await expect(evasion.locator('..')).toContainText(`Итог: ${bonus?11:10}`);
  await evasion.fill('9');await evasion.press('Tab');
  const proficiency=editor.getByRole('spinbutton',{name:'Мастерство',exact:true});await proficiency.fill('2');await proficiency.press('Tab');
  await editor.getByRole('button',{name:'Готово',exact:true}).click();
  await expect(editor.getByLabel('Ключевые параметры').locator('.inline-stat').filter({hasText:'Уклонение'}).locator('strong')).toHaveText(bonus?'10':'9');
  await expect(editor.getByLabel('Ключевые параметры').locator('.inline-stat').filter({hasText:'Мастерство'}).locator('strong')).toHaveText('2');
  await editor.getByRole('button',{name:'Редактировать',exact:true}).click();await expect(editor.getByRole('spinbutton',{name:'Мастерство',exact:true})).toHaveValue('2');
  await editor.getByRole('button',{name:'Удалить персонажа '+hero.name,exact:true}).click();
  await page.getByRole('dialog',{name:/Удалить персонажа/}).getByRole('button',{name:'Отмена',exact:true}).click();
  await expect(editor.getByRole('heading',{name:hero.name,exact:true})).toBeVisible();
  await editor.getByRole('button',{name:'Готово',exact:true}).click();
  await expect(editor.locator('.character-editor-domains')).toContainText('Домены:');
});
