import { expect, test } from '@playwright/test';
import { createPopulatedGameDocument, filledCharacterName, importGameDocument } from './filled-game-helpers';
import { openGmGame } from './game-route-helpers';
import { openGameLibrary } from './tools-helpers';
const before = process.env.CHARACTER_LAYOUT_BEFORE === '1';
const firstName = 'QA — Серафим';
const longName = 'QA — Смешанный с очень длинным именем персонажа';
const out = '/home/codex/outputs/dh-character-library-layout-20261027';
for (const width of [1180, 1440, 390]) test(`character list and editor remain usable at ${width}`, async ({ page }) => {
  await page.setViewportSize({ width, height: width === 1180 ? 757 : 900 });
  await openGmGame(page);
  const doc = createPopulatedGameDocument();
  const characters = doc.files['data/characters.json'];
  characters.entities[characters.order[0]].name = firstName;
  characters.entities[characters.order[1]].name = longName;
  characters.entities[characters.order[2]].name = filledCharacterName;
  const seats = doc.files['data/scene-table.json'].participants;
  seats['e2e-seat-1'].name = firstName;
  seats['e2e-seat-2'].name = 'Ольга — игрок';
  await importGameDocument(page, doc, 'character-library-layout.dhgame');
  const library = await openGameLibrary(page);
  await library.getByLabel('Разделы библиотеки').getByRole('button', { name: 'Персонажи', exact: true }).click();
  const roster = library.getByRole('navigation', { name: 'Ростер персонажей', exact: true });
  const first = roster.locator('.player-tools-character-card').filter({ has: page.getByRole('button', { name: firstName, exact: true }) });
  const second = roster.locator('.player-tools-character-card').filter({ has: page.getByRole('button', { name: longName, exact: true }) });
  await page.screenshot({ path: `${out}/${before ? 'before' : 'after'}-${width}-roster.png` });
  await first.getByRole('button', { name: firstName, exact: true }).click();
  const editor = library.getByRole('region', { name: 'Редактор персонажа', exact: true });
  await editor.getByRole('button', { name: 'Редактировать', exact: true }).click();
  await editor.getByLabel('Разделы листа персонажа').getByRole('button', { name: 'Характеристики', exact: true }).click();
  await page.screenshot({ path: `${out}/${before ? 'before' : 'after'}-${width}-editor.png` });
  if (before) return;
  const traits = editor.locator('.trait-card');
  await expect(traits).toHaveCount(6);
  const traitMetrics = await traits.evaluateAll(cards => cards.map(card => {
    const label = card.querySelector('span')!, select = card.querySelector('select')!;
    const l = label.getBoundingClientRect(), s = select.getBoundingClientRect(), c = card.getBoundingClientRect();
    return { textWidth: label.scrollWidth, available: label.clientWidth, labelBottom: l.bottom, inputTop: s.top, inputRight: s.right, cardRight: c.right, labelRight: l.right, inputLeft: s.left, inputWidth: s.width };
  }));
  for (const m of traitMetrics) {
    expect(m.textWidth).toBeLessThanOrEqual(m.available + 1);
    expect(m.labelBottom).toBeLessThanOrEqual(m.inputTop);
    expect(m.inputRight).toBeLessThanOrEqual(m.cardRight);
    expect(m.inputWidth).toBeGreaterThanOrEqual(70);
  }
  await expect(editor.getByRole('heading', { name: firstName, exact: true })).toBeVisible();
  await editor.getByRole('button', { name: 'Готово', exact: true }).click();
  await expect(editor.getByRole('button', { name: 'Редактировать', exact: true })).toBeVisible();
  const back = library.getByRole('button', { name: 'Вернуться к ростеру персонажей', exact: true });
  if (width <= 1120) await back.click();
  await expect(first.locator('.dh-list-item__detail')).toHaveCount(0);
  await expect(second.locator('.dh-list-item__detail')).toHaveText('Игрок: Ольга — игрок');
  const remove = second.getByRole('button', { name: 'Убрать со сцены', exact: true });
  await remove.click();
  await expect(second.getByRole('button', { name: 'На сцену', exact: true })).toBeVisible();
  await expect(first).toHaveClass(/dh-is-selected/);
  await second.getByRole('button', { name: 'На сцену', exact: true }).click();
  await expect(remove).toBeVisible();
  await second.getByRole('button', { name: longName, exact: true }).click();
  await expect(editor.getByRole('heading', { name: longName, exact: true })).toBeVisible();
  await page.screenshot({ path: `${out}/after-${width}-long-name.png` });
  expect(await page.locator('body').evaluate(el => el.scrollWidth)).toBeLessThanOrEqual(width);
});
